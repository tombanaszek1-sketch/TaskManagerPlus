export type MessageKey = keyof typeof en;
type Dictionary = Record<MessageKey, string>;

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

/** All interface text lives in one English dictionary; `vars` fill `{name}` placeholders. */
export function createTranslator(dictionary: Dictionary = en): Translate {
  return (key, vars) => {
    let text: string = dictionary[key] ?? en[key];
    if (vars) {
      for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
    }
    return text;
  };
}

export const I18nContext = createContext<{ t: Translate }>({ t: createTranslator() });

export function useI18n() {
  return useContext(I18nContext);
}
